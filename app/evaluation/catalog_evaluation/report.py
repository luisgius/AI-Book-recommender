"""Markdown report of the catalog evaluation, rendered from the results document only."""

from typing import Any, Dict, List, Mapping, Optional, Sequence

from app.evaluation.catalog_evaluation import design as D

JUDGE_NAME = {"primary": f"primary judge `{D.PRIMARY_JUDGE}`", "second": f"second judge `{D.SECOND_JUDGE}`"}


def _f(value: Optional[float], digits: int = 3, signed: bool = False) -> str:
    if value is None:
        return "n/a"
    return f"{value:+.{digits}f}" if signed else f"{value:.{digits}f}"


def _p(value: Optional[float]) -> str:
    if value is None:
        return "n/a"
    return "<0.001" if value < 0.001 else f"{value:.3f}"


def _ci(ci: Sequence[float], signed: bool = False) -> str:
    return f"[{_f(ci[0], signed=signed)}, {_f(ci[1], signed=signed)}]"


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> List[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return lines + [""]


def _usd(value: Optional[float]) -> str:
    return "n/a" if value is None else f"{value:.4f}"


def build_markdown(r: Mapping[str, Any], meta: Mapping[str, Any]) -> str:
    L: List[str] = []
    spend = r["spend"]
    L += ["# Evaluation on the deployed catalog (V14)", ""]
    L += [f"- Protocol: `{r['protocol']['path']}`, committed in `{r['protocol']['commit']}` before any result. "
          "This report implements it; every deviation is listed in [Deviations from the protocol](#deviations-from-the-protocol).",
          "- **Relevance judgments come from LLM judges only.** The human annotation sheet (200 pairs) has been produced "
          "but not filled; until it is, no agreement with people has been measured on this catalog.",
          f"- Date of the runs: {meta.get('date', 'n/a')}. Report regenerated offline from the saved files "
          "(`python -m app.evaluation.catalog_evaluation report --offline`).",
          f"- Collection: Neon schema `{D.SCHEMA}`, {D.CATALOG_WORKS:,} works; adapters called directly (no public URL).",
          "- Models and providers (all through OpenRouter): "
          f"query generator `{(r['queries'].get('generator') or {}).get('model', 'n/a')}`; "
          f"embeddings `{D.QWEN_EMBEDDING}` (1024 d) and `{D.BGE_EMBEDDING}`, both pinned to {D.EMBEDDING_PIN}; "
          f"reranker `{D.RERANKER}` pinned to {D.RERANKER_PIN}; system LLM `{D.SYSTEM_LLM}`; "
          f"judges `{D.PRIMARY_JUDGE}` (primary) and `{D.SECOND_JUDGE}` (second), reasoning effort low.",
          f"- Real spend reported by OpenRouter: **{_usd(spend['total_usd'])} USD** over {spend['calls']} calls "
          f"(cap {D.SPEND_CAP_USD:.2f} USD). By stage in [Cost](#cost-and-time).", ""]

    # ---------------------------------------------------------------- summary
    L += ["## Summary", ""]
    for line in meta.get("summary", []):
        L.append(f"- {line}")
    L.append("")

    # ---------------------------------------------------------------- queries
    q = r["queries"]
    L += ["## Queries", ""]
    rows = [[s, q["counts_by_stratum"].get(s, 0), D.EXPECTED_COUNTS[s]] for s in ("A", "B", "C", "D")]
    L += _table(["Stratum", "Queries", "Declared"], rows)
    langs = sorted({k.split("/")[1] for k in q["counts_by_stratum_language"]})
    L += ["Queries per language and stratum:", ""]
    L += _table(["Language"] + list("ABCD"), [[lang] + [q["counts_by_stratum_language"].get(f"{s}/{lang}", 0) for s in "ABCD"]
                                             for lang in langs])
    types = sorted({k.split("/")[1] for k in q["counts_by_stratum_type"]})
    L += _table(["Type"] + list("ABCD"), [[t] + [q["counts_by_stratum_type"].get(f"{s}/{t}", 0) for s in "ABCD"] for t in types])
    gen = q.get("generator") or {}
    L += [f"Strata B, C and D were generated by `{gen.get('model')}` (temperature {gen.get('temperature')}, reasoning "
          f"{gen.get('reasoning')}), a vendor used nowhere else in the evaluation, from the catalog's language shares and "
          "its 60 most frequent subjects only; prompts, raw outputs and dates are in `data/evaluation/catalog50k/queries/generation/`.",
          "", "Mechanical checks (counts, duplicates, language of the query, title words in known-item queries, known item "
          "present in the catalog). Problems after the first pass:", ""]
    for p in q.get("first_pass_problems") or []:
        L.append(f"- `{p['query_id']}` {p['check']}: {p['detail']}")
    L += ["", f"Replacements requested from the generator ({len(q.get('fixes') or [])}, every one logged in `checks.json`):", ""]
    for fix in q.get("fixes") or []:
        after = (fix.get("after") or {}).get("text", fix.get("error"))
        L.append(f"- round {fix['round']}, `{fix['query_id']}` ({'; '.join(fix['reasons'])[:160]}) -> \"{after}\"")
    L += ["", f"Problems in the final set: {len(q.get('final_problems') or [])}. Language verdicts: {q.get('language_summary')}. "
          "The undecided ones are short keyword queries with no function word; each was read by hand and is in its stated "
          "language: " + ", ".join(f"`{k}`" for k in sorted(q.get("language_undecided") or {})) + ".", ""]
    missing = [k for k, v in (q.get("known_item_targets") or {}).items() if not v]
    L += [f"Known-item targets found in the catalog by title: {sum(1 for v in (q.get('known_item_targets') or {}).values() if v)} "
          f"of {len(q.get('known_item_targets') or {})}. " + (meta.get("known_item_note", "") if missing else ""), ""]
    for note in meta.get("query_notes", []):
        L.append(f"- {note}")
    L.append("")

    # ---------------------------------------------------------------- systems
    L += ["## Systems and runs", ""]
    L += _table(["Id", "System"], [[s.name, s.description] for s in D.SYSTEMS])
    par = r.get("parity") or {}
    pp = par.get("parity") or {}
    ex = par.get("explain") or {}
    L += [f"- Local catalog copy vs Neon (`parity`): {pp.get('local_works')} and {pp.get('neon_works')} works, same ids "
          f"{pp.get('same_ids')}, embedded text equal (text_hash) for {pp.get('text_hash_equal')}, content equal for "
          f"{pp.get('content_hash_equal')}. Works are hydrated from the local copy; E2 encodes exactly the loader's text.",
          f"- Approximate index of the schema: `{par.get('vector_index')}` (Neon's IVF index), uses the index in EXPLAIN: "
          f"{ex.get('approximate_uses_ann_index')}.",
          f"- E1: index scans disabled for the statement ({ex.get('exact_settings')}); EXPLAIN shows a sequential scan "
          f"without the ANN index: {ex.get('exact_is_sequential_scan')}. Plan (vector literal shortened):", "", "```"]
    for line in ex.get("exact_plan") or []:
        L.append(line.split("'[")[0] + ("'[...]'::halfvec))" if "'[" in line else ""))
    L += ["```", ""]
    fails = r["runs"]["failures"]
    L += ["Run files (`data/evaluation/catalog50k/runs/`, 100 results per query) and failures:", ""]
    L += _table(["System", "Queries", "Fallbacks (call failed 3 times, input order kept)", "Notes"],
                [[s, fails[s]["queries"], len(fails[s]["fallbacks"]),
                  ", ".join(f"{k} {v}" for k, v in fails[s].items() if k not in ("queries", "fallbacks")) or "-"]
                 for s in D.SYSTEM_NAMES if s in fails])
    lat = r["runs"]["latency_ab"]
    stages = ["lexical", "embedding", "vector", "fusion", "rerank", "llm"]
    L += ["Latency per stage, median over the 116 queries of A and B (ms). The embedding is the frozen call, made with "
          "the evaluation's long deadlines; Neon calls were sequential from this laptop.", ""]
    L += _table(["System"] + stages + ["total median", "total p95"],
                [[s] + [_f(lat[s]["median_ms"].get(st), 1) if st in lat[s]["median_ms"] else "-" for st in stages]
                 + [_f(lat[s]["total_median_ms"], 1), _f(lat[s]["total_p95_ms"], 1)] for s in D.SYSTEM_NAMES if s in lat])

    # ---------------------------------------------------------------- judgments
    j = r["judgments"]
    pool = r["pool"]
    ag = j["agreement"]
    L += ["## Pool and judgments", "",
          f"Pool: union of the top {D.POOL_K} of {', '.join(D.POOL_SYSTEMS)} per need: {pool['needs']} needs, "
          f"{pool['pairs']} (need, work) pairs (per need: median {pool['per_need'].get('median')}, min "
          f"{pool['per_need'].get('min')}, max {pool['per_need'].get('max')}). Pairs by stratum: {pool['pairs_by_stratum']}.", ""]
    rows = []
    for label in ("primary", "second"):
        runs = [x for x in j["runs"] if x.get("model") == j[label]["model"]]
        rows.append([f"`{j[label]['model']}`", label, j[label]["graded_pairs"],
                     sum(x.get("failed_calls_in_run", 0) for x in runs), runs[-1].get("unjudged") if runs else "n/a",
                     j["grade_distribution"][label]])
    L += _table(["Judge", "Role", "Pairs graded", "Failed calls (retried)", "Left unjudged", "Grades"], rows)
    if ag.get("pairs"):
        o = ag["overall"]
        L += [f"Agreement between the judges on {ag['pairs']} pairs: quadratic-weighted kappa {_f(o['quadratic_weighted_kappa'])} "
              f"{_ci(o['quadratic_weighted_kappa_ci95'])} (bootstrap over pairs), exact agreement {_f(o['exact_agreement'])}, "
              f"within one grade {_f(o['within_one_agreement'])}, mean difference (second - primary) "
              f"{_f(o['mean_signed_difference'], signed=True)}. Binary kappa at grade >= 1: "
              f"{_f(o['binary']['at_least_1']['kappa'])}, at >= 2: {_f(o['binary']['at_least_2']['kappa'])}. "
              f"Confusion matrix (rows primary 0-3, columns second 0-3): {o['confusion_matrix']}.", ""]
        by = ag.get("by_language") or {}
        if by:
            L += _table(["Need language", "Pairs", "Kappa (quadratic)", "Exact"],
                        [[k, v["n"], _f(v["quadratic_weighted_kappa"]), _f(v["exact_agreement"])] for k, v in sorted(by.items())])

    # ---------------------------------------------------------------- results
    L += ["## Results on strata A and B (116 queries)", ""]
    for label in ("primary", "second"):
        m = r["metrics"][label]["summary_ab"]
        L += [f"Under the {JUDGE_NAME[label]}:", ""]
        L += _table(["System", "nDCG@10 [95 % CI]", "P@10", "MRR@10", "Recall@100 (pool)", "Judged@10"],
                    [[s, f"{_f(m[s]['ndcg_at_10']['mean'])} {_ci(m[s]['ndcg_at_10']['ci'])}",
                      _f(m[s]["p_at_10"]["mean"]), _f(m[s]["mrr_at_10"]["mean"]), _f(m[s]["recall_at_100"]["mean"]),
                      _f(m[s]["judged_at_10"]["mean"])] for s in D.SYSTEM_NAMES if s in m])

    L += ["## Declared contrasts H1-H6", "",
          "nDCG@10 difference (system - baseline) on A and B, 95 % paired bootstrap interval, two-sided paired "
          "randomisation test (10,000 resamples, seed 0) and Holm correction over H1-H6, under each judge. Rule of the "
          "protocol: a conclusion holds only if it has the same sign and is significant (Holm) under both judges; if the "
          "judges disagree it is not conclusive.", ""]
    rows = []
    for c in list(D.CONTRASTS) + [D.REPLICATION]:
        cells = [c.name, f"{c.system} - {c.baseline}"]
        for label in ("primary", "second"):
            row = r["metrics"][label]["contrasts"].get(c.name)
            cells += [f"{_f(row['difference'], signed=True)} {_ci(row['ci'], True)}", _p(row["p"]),
                      _p(row["p_holm"]) if row["in_family"] else "(outside)"]
        cells.append(r["conclusions"].get(c.name, "n/a"))
        rows.append(cells)
    L += _table(["", "Contrast", "Primary: diff [CI]", "p", "p Holm", "Second: diff [CI]", "p", "p Holm", "Outcome"], rows)
    for line in meta.get("contrast_notes", []):
        L.append(f"- {line}")
    L.append("")
    hr = r.get("hybrid_rule")
    if hr:
        L += [f"Rule for the hybrid fusion (protocol section 8): the thesis text says what H1 says; the deployed "
              f"pipeline keeps BM25 unless S4 beats S5 significantly. S4 significantly better than S5 under both "
              f"judges: **{hr['s4_significantly_better_than_s5']}**. Outcome: **{hr['outcome']}**. The deployment was "
              "not changed by this task.", ""]
    rep = r["metrics"]["primary"]["s6_replication"]
    L += [f"S6 replication: the two runs of the LLM re-ranker gave the same top 10 for {rep['identical_top10']} of "
          f"{rep['queries']} queries; mean absolute nDCG@10 difference per query {_f(rep['mean_abs_ndcg_difference'])} "
          "(primary judge). H5-rep repeats H5 with the second run, outside the Holm family.", ""]

    # ---------------------------------------------------------------- breakdowns
    L += ["## By language and by query type (descriptive, primary judge)", ""]
    bl = r["metrics"]["primary"]["by_language"]
    L += _table(["Language", "Queries"] + list(D.SYSTEM_NAMES),
                [[k, v["queries"]] + [_f(v.get(s)) for s in D.SYSTEM_NAMES] for k, v in bl.items()])
    bt = r["metrics"]["primary"]["by_type"]
    L += _table(["Type", "Queries"] + list(D.SYSTEM_NAMES),
                [[k, v["queries"]] + [_f(v.get(s)) for s in D.SYSTEM_NAMES] for k, v in bt.items()])
    bl2 = r["metrics"]["second"]["by_language"]
    L += ["Same by language under the second judge:", ""]
    L += _table(["Language", "Queries"] + list(D.SYSTEM_NAMES),
                [[k, v["queries"]] + [_f(v.get(s)) for s in D.SYSTEM_NAMES] for k, v in bl2.items()])
    ov = r["overlap_s2_e1"]
    L += ["## Cost of the approximate index (S2 against E1)", "",
          f"Mean share of E1's top 10 that S2 also returns: {_f(ov['top10'])} on A and B ({_f(ov['all_queries_top10'])} on "
          f"all 168 queries); top 100: {_f(ov['top100'])}. nDCG@10 S2 vs E1 is in the tables above.", ""]
    c = r["metrics"]["primary"]["stratum_c"]
    L += ["## Stratum C: the same need in four languages (descriptive)", "",
          f"{c['needs']} needs x {len(D.C_LANGUAGES)} languages; judgments shared by the four versions. nDCG@10 per "
          "language (primary judge) and mean pairwise overlap of the top 10 between versions of a need:", ""]
    L += _table(["System"] + list(D.C_LANGUAGES) + ["top-10 overlap"],
                [[s] + [_f(c["ndcg_at_10_by_language"][s].get(l)) for l in D.C_LANGUAGES]
                 + [_f(c["mean_pairwise_top10_overlap"].get(s))] for s in D.SYSTEM_NAMES])

    # ---------------------------------------------------------------- operational
    L += ["## Embedding model: operational measurements and decision rule (section 8)", ""]
    op = r.get("operational")
    if op:
        L += [f"Each of the 168 queries encoded {D.OPERATIONAL_REPETITIONS} times per model with the deployed deadlines "
              f"({D.DEPLOYED_TIMEOUT_S:g} s per attempt, {D.DEPLOYED_RETRIES} retry, {D.DEPLOYED_DEADLINE_S:g} s per call), "
              "no cache, one call at a time per model; top 10 by the model's exact search.", ""]
        L += _table(["Model", "Calls", "Median ms", "p95 ms", "Failed or timed out", "Queries whose vector changed",
                      "Queries whose top 10 changed (of compared)"],
                    [[f"`{m}`", v["calls"], _f(v["median_ms"], 0), _f(v["p95_ms"], 0), v["failed_calls"],
                      v["queries_vector_changed"], f"{v['queries_top10_changed']} ({v['queries_compared']})"]
                     for m, v in op.items()])
        dr = r.get("decision_rule")
        if dr:
            L += [f"- Condition 1 (H6 does not show qwen significantly better under either judge): **{dr['condition_1_h6']}**.",
                  f"- Condition 2 (bge-m3 better on at least two criteria and not >10 % worse on the third): "
                  f"**{dr['condition_2_operational']}**; bge-m3 better on {dr['bge_better_on'] or 'none'}; "
                  + "; ".join(f"{k}: better {v['better']}, worse by >10 % {v['worse_over_10pct']}" for k, v in dr["criteria"].items()) + ".",
                  f"- **Outcome of the rule: {dr['outcome']}.** The deployed model was not changed by this task.", ""]
    else:
        L += ["Not measured.", ""]

    # ---------------------------------------------------------------- unanswerable
    u = r.get("unanswerable")
    L += ["## Unanswerable queries (section 9, exploratory)", ""]
    if u:
        recl = [k for k, v in u["reclassification"].items() if v["reclassified"]]
        L += [f"Stratum D queries reclassified because the primary judge gave grade 2 or 3 to some pooled work: "
              f"{', '.join(recl) or 'none'}. Per query (works graded 2-3 by primary / second judge): "
              + ", ".join(f"{k} {v['primary_works_graded_2_or_3']}/{v['second_works_graded_2_or_3']}" for k, v in u["reclassification"].items()) + ".",
              f"Answered A and B queries (some work graded >= 2 by the primary judge): {u['answered_ab_queries']} of 116; "
              f"without an answer: {', '.join(u['ab_without_answer']) or 'none'}.", ""]
        a, n = u["answered_scores"], u["unanswerable_scores"]
        L += _table(["Group", "n", "min", "median", "mean", "max"],
                    [["answered (A, B)", a.get("n"), _f(a.get("min")), _f(a.get("median")), _f(a.get("mean")), _f(a.get("max"))],
                     ["unanswerable (D kept)", n.get("n"), _f(n.get("min")), _f(n.get("median")), _f(n.get("mean")), _f(n.get("max"))]])
        bt_ = u.get("best_threshold") or {}
        L += [f"Score: the reranker's score of the first result of S5. AUC {_f(u['auc'])}. Best threshold on these data "
              f"(Youden's J): {_f(bt_.get('threshold'), 4)} (TPR {_f(bt_.get('tpr'))}, FPR {_f(bt_.get('fpr'))}, accuracy "
              f"{_f(bt_.get('accuracy'))}). The threshold is chosen and measured on the same data, so nothing is claimed "
              "about its performance elsewhere.", ""]

    # ---------------------------------------------------------------- explanations
    e = r.get("explanations")
    L += ["## Explanations (section 10)", ""]
    if e:
        s = e["v10_summary"]
        L += [f"{e['queries']} queries of A and B drawn with seed 0, top {D.EXPLANATION_RESULTS} of S5, `{D.SYSTEM_LLM}` "
              f"through the deployed client: {e['records']} explanations, {s.get('parsed')} parsed. Citation precision "
              f"before the guardrail (V10 procedure): {_f(s.get('citation_precision'))} over {s.get('citations')} citations; "
              f"explanations without a valid citation: {_f(s.get('zero_valid_share'))}. In the query's language "
              f"(catalog language detector on summary and reasoning): {e['in_query_language']} of {e['parsed']} "
              f"({e['language_undecided']} undecided). Detected languages: {e['detected_languages']}.", ""]
        L += _table(["Query language", "In that language", "Explanations"],
                    [[k, v["in_language"], v["explanations"]] for k, v in sorted(e["in_query_language_by_language"].items())])
    else:
        L += ["Not run.", ""]

    # ---------------------------------------------------------------- annotation
    an = r.get("annotation") or {}
    L += ["## Human annotation sheet", "",
          f"`data/evaluation/catalog50k/annotation/annotation_sheet.csv`: {an.get('pairs')} pairs drawn from the "
          f"{an.get('population')} judged pairs of A and B (seed 0, stratified by language and primary grade, shuffled), "
          "no judge grade shown; instructions in Spanish in `INSTRUCCIONES.md`. After filling it: "
          "`.venv/bin/python -m app.evaluation.catalog_evaluation annotation-agreement --sheet <file>`.", ""]
    ha = r.get("human_agreement")
    if ha:
        for model, v in ha["judges"].items():
            if v.get("pairs"):
                L.append(f"- Human vs `{model}`: {v['pairs']} pairs, quadratic kappa {_f(v['overall']['quadratic_weighted_kappa'])} {_ci(v['overall']['quadratic_weighted_kappa_ci95'] or [None, None])}, exact {_f(v['overall']['exact_agreement'])}.")
        L.append("")

    # ---------------------------------------------------------------- cost
    L += ["## Cost and time", ""]
    L += _table(["Stage", "Calls", "Failed", "Without reported cost", "USD"],
                [[k, v["calls"], v["failed_calls"], v["calls_without_cost"], _usd(v["cost_usd"])] for k, v in sorted(spend["by_stage"].items())]
                + [["total", spend["calls"], "", "", _usd(spend["total_usd"])]])
    L += _table(["Model", "Calls", "USD"], [[f"`{k}`", v["calls"], _usd(v["cost_usd"])] for k, v in sorted(spend["by_model"].items())])
    snaps = [s for s in spend.get("key_usage_snapshots") or [] if s.get("key_usage_usd") is not None]
    if len(snaps) >= 2:
        L += [f"Cross-check: the key's cumulative usage reported by OpenRouter went from {_usd(snaps[0]['key_usage_usd'])} to "
              f"{_usd(snaps[-1]['key_usage_usd'])} USD across the stages ({_usd(snaps[-1]['key_usage_usd'] - snaps[0]['key_usage_usd'])} "
              "USD; other use of the key in that window, if any, is included, and the counter can lag).", ""]
    L += ["Wall-clock time per stage (s, summed over resumed runs): "
          + ", ".join(f"{k} {v:.0f}" for k, v in sorted(r.get("stage_seconds", {}).items())) + ".", ""]
    for line in meta.get("time_notes", []):
        L.append(f"- {line}")
    L.append("")

    L += ["## Deviations from the protocol", ""]
    for i, d in enumerate(meta.get("deviations", []), start=1):
        L.append(f"{i}. {d}")
    L += ["", "## Limits", ""]
    for line in meta.get("limits", []):
        L.append(f"- {line}")
    L += ["", "## Files", ""]
    for line in meta.get("files", []):
        L.append(f"- {line}")
    L.append("")
    return "\n".join(L)
